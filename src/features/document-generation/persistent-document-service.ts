export const GENERATED_DOCUMENT_BUCKET = "candidate-documents-private";
export const MAX_GENERATED_PDF_BYTES = 10 * 1024 * 1024;
export type PersistedOutputKind = PdfOutputKind | "global-ats-employer-masked";
export type RegenerationLease = { jobId: string; token: string; revision: number };

type Rendered = { model: PdfDocumentModel; theme?: PdfThemeOverrides; filename: string };
export type PersistedPdf = { id: string; version: number; bytes: Uint8Array; filename: string };

const digest = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");

/** The upload validator's hardened signature/trailer rule also applies to generated bytes. */
export function assertGeneratedPdf(bytes: Uint8Array): void {
  if (!bytes.length || bytes.length > MAX_GENERATED_PDF_BYTES ||
      !hasSupportedFileSignature(bytes, "pdf")) {
    throw new Error("Generated PDF failed integrity validation.");
  }
}

async function profileRevision(profileId: string): Promise<number> {
  const { data, error } = await createSupabaseAdminClient().from("candidate_profiles")
    .select("career_revision").eq("id", profileId).is("archived_at", null).maybeSingle();
  if (error || !data || !Number.isSafeInteger(data.career_revision)) throw new Error("Career revision is unavailable.");
  return data.career_revision;
}

async function loadStableProfile(profileId: string): Promise<{ profile: CandidateProfile; revision: number }> {
  const before = await profileRevision(profileId);
  const profile = await loadCandidateProfileById(profileId);
  const after = await profileRevision(profileId);
  if (!profile || before !== after) throw new Error("Profile changed during document preparation. Retry.");
  return { profile, revision: after };
}

async function buildOutput(profile: CandidateProfile, output: PersistedOutputKind): Promise<Rendered> {
  const masked = output === "global-ats-employer-masked";
  const standard = masked ? "global-ats-resume" : output;
  if (!packageAllowsOutput(profile.selectedPackage, standard)) throw new Error("Package does not include this output.");
  const mapping = mapCandidateProfileToDocumentData(profile, standard.endsWith("cover-letter") ? "cover-letter" : "resume");
  if (masked) {
    const { model, referenceId } = buildPrivacyMaskedEmployerResume(mapping);
    return { model, filename: buildPdfFilename({ candidateName: referenceId,
      output: "global-ats-resume", privacyMasked: true }) };
  }
  const filename = buildPdfFilename({ candidateName: profile.fullName, output: standard });
  if (standard === "global-ats-resume") return { model: buildGlobalAtsResumeModel(mapping), filename };
  if (standard.startsWith("domestic-resume-")) {
    const design = standard.slice("domestic-resume-".length) as DomesticDesignId;
    const result = buildDomesticResumeModel(mapping, design);
    return { ...result, filename };
  }
  if (standard === "gcc-resume") {
    // The caller has already resolved an authorized profile. Never accept a
    // browser-supplied photo key or expose the private source object.
    const photo = await loadTrustedGccPhoto(profile.id);
    const trusted = photo ? mapCandidateProfileToDocumentData({ ...profile, gccPhoto: photo.reference }, "resume") : mapping;
    const uri = photo ? `data:image/png;base64,${Buffer.from(photo.png).toString("base64")}` : undefined;
    return { ...buildGccResumeModel(trusted, uri), filename };
  }
  if (standard === "europass-eu-resume") return { ...buildEuropeanResumeModel(mapping), filename };
  const type = standard.slice(0, -"-cover-letter".length) as
    "general-corporate" | "international-relocation" | "technology-startup";
  return { ...buildCoverLetterModel(mapping, type), filename };
}

/** Store, read back, and atomically publish only verified private PDF bytes. */
export async function generateAndPersistDocument(
  profileId: string, output: PersistedOutputKind,
  options: { actorUserId: string; job?: RegenerationLease } = { actorUserId: "" },
): Promise<PersistedPdf> {
  if (!options.actorUserId) throw new Error("A verified actor is required.");
  if (process.env.NODE_ENV === "production") {
    await (await import("@/lib/security/rate-limit")).enforceRateLimit("pdf-generation", options.actorUserId, 40);
  }
  const { profile, revision } = await loadStableProfile(profileId);
  if (options.job && options.job.revision !== revision) throw new Error("Regeneration job is stale.");
  const atsMapping = mapCandidateProfileToDocumentData(profile, "resume");
  await recordIndicativeAtsAssessment(profileId, revision, calculateIndicativeAtsScore(atsMapping));
  const db = createSupabaseAdminClient();
  let sourceId: string | null = null;
  if (output === "global-ats-employer-masked") {
    const { data: source, error } = await db.from("document_records")
      .select("id").eq("candidate_profile_id", profileId).eq("output_kind", "global-ats-resume")
      .eq("source_career_revision", revision).eq("status", "available")
      .is("archived_at", null).maybeSingle();
    if (error) throw new Error("The source resume could not be verified.");
    sourceId = source?.id ?? (await generateAndPersistDocument(profileId, "global-ats-resume",
      { actorUserId: options.actorUserId })).id;
  }
  const { model, theme, filename } = await buildOutput(profile, output);
  const bytes = new Uint8Array(await renderPdfDocument(model, theme));
  assertGeneratedPdf(bytes);
  const { data: bucket, error: bucketError } = await db.storage.getBucket(GENERATED_DOCUMENT_BUCKET);
  if (bucketError || !bucket || bucket.public) throw new Error("The private document bucket is unavailable.");
  const documentId = randomUUID();
  const fileId = randomUUID();
  const objectKey = `${profileId}/${documentId}/${fileId}.pdf`;
  const storage = db.storage.from(GENERATED_DOCUMENT_BUCKET);
  const { error: uploadError } = await storage.upload(objectKey, bytes,
    { contentType: "application/pdf", upsert: false, cacheControl: "0" });
  if (uploadError) throw new Error("The private document upload failed.");
  try {
    const { data: verified, error: readError } = await storage.download(objectKey);
    if (readError || !verified) throw new Error("The stored PDF could not be verified.");
    const stored = new Uint8Array(await verified.arrayBuffer());
    if (stored.length !== bytes.length || digest(stored) !== digest(bytes)) {
      throw new Error("The stored PDF failed verification.");
    }
    const { data, error } = await db.rpc("publish_generated_document", {
      p_profile_id: profileId, p_output_kind: output, p_document_id: documentId,
      p_file_id: fileId, p_object_key: objectKey, p_file_name: filename,
      p_byte_size: bytes.length, p_career_revision: revision,
      p_package_code: profile.selectedPackage, p_mask_source_id: sourceId,
      p_job_id: options.job?.jobId ?? null, p_lease_token: options.job?.token ?? null,
    });
    if (error || !Array.isArray(data) || data[0]?.published_document_id !== documentId) {
      throw new Error("The generated PDF could not be published.");
    }
    // Audit is best-effort after publication; it must never cause cleanup of
    // a successfully committed Storage/DB pair.
    if (process.env.NODE_ENV === "production") {
      try {
        await (await import("@/lib/security/audit-events")).recordSecurityEvent({
          eventType: output === "global-ats-employer-masked" ? "document.privacy_generated" : "document.generated",
          actorUserId: options.actorUserId, candidateProfileId: profileId, outcome: "success",
        });
      } catch { /* Publication remains authoritative. */ }
    }
    return { id: documentId, version: data[0].published_version, bytes, filename };
  } catch (error) {
    // An RPC transport failure is ambiguous: it may have committed in Postgres.
    // Never delete a possibly published object. Inconclusive checks leave a
    // private orphan for reconciliation, never a broken current document.
    const published = await db.from("document_records").select("id, version_number")
      .eq("id", documentId).eq("file_record_id", fileId).maybeSingle();
    if (published.error) throw new Error("Publication outcome requires operational review.");
    if (published.data) return { id: documentId, version: published.data.version_number, bytes, filename };
    const { error: cleanupError } = await storage.remove([objectKey]);
    if (cleanupError) throw new Error("Document publication failed and private cleanup requires review.");
    throw error;
  }
}

/** Recheck admin authority at the mutation boundary, not just the route loader. */
export async function generateAndPersistAdminDocument(profileId: string,
  output: PersistedOutputKind): Promise<PersistedPdf> {
  const actor = await requireApplicationRole("admin");
  if (!actor.userId) throw new Error("Document access denied.");
  return generateAndPersistDocument(profileId, output, { actorUserId: actor.userId });
}
